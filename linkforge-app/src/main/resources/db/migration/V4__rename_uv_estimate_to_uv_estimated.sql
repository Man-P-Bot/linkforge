-- =============================================================================
-- 阶段 3：把 uv_estimate 改名为 uv_estimated
--
-- 为什么改：
--   本阶段的 UV 语义是「当日独立访客的**估算值**」（HyperLogLog PFCOUNT 的结果），
--   不是一个精确计数。字段名带 -ed 后缀能让读 SQL 的人一眼看出这是估算值，
--   避免下游误以为它可以精确对账（实际误差约 0.81%）。
--
-- ⚠️ 为什么用新迁移而不是改 V1：
--   V1 已经在开发库与测试库上应用过（flyway_schema_history 里有 checksum）。
--   改已应用的迁移会导致 Flyway 校验和不匹配而**启动失败**。
--   正确做法是新增一个向前迁移。
--
-- ⚠️ 为什么现在改名是安全的：
--   link_stats_daily 当前是空表（0 行），且阶段 3 之前没有任何代码读写它。
--   即使有数据，RENAME COLUMN 也不丢数据（MySQL 8.0+ 的 RENAME COLUMN 是元数据操作）。
-- =============================================================================

ALTER TABLE link_stats_daily
    RENAME COLUMN uv_estimate TO uv_estimated;
